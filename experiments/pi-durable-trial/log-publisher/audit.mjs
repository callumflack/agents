import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { join } from 'node:path';

const run = process.argv[2];
const read = name => JSON.parse(readFileSync(join(run, name)));
const hash = path => createHash('sha256').update(readFileSync(path)).digest('hex');
const input = read('input.json');
const receipt = read('push-receipt.json');
const git = (...args) => {
  const result = spawnSync(input.git, args, { cwd: input.workspace, encoding: 'utf8' });
  assert.equal(result.status, 0, result.stderr);
  return result.stdout.trim();
};
const events = readFileSync(join(run, 'git-events.jsonl'), 'utf8').trim().split('\n').map(JSON.parse);
assert.equal(events.filter(event => event.kind === 'commit').length, 1);
assert.equal(events.filter(event => event.kind === 'push-succeeded').length, 1);
assert.equal(git('rev-list', '--count', input.baseline + '..' + receipt.commit), '1');
assert.equal(git('diff', '--name-only', input.baseline, receipt.commit), input.snapshot);
assert.equal(git('ls-remote', 'origin', 'refs/heads/main').split(/\s+/)[0], receipt.commit);
assert.equal(read('recovered-2.json').state.status, 'pending');
assert.equal(read('recovered-2.json').state.checkpoint.phase, 'publish');
assert.equal(read('reconciliation.json').remote, receipt.commit);
const settled = read('settled-2.json');
assert.equal(settled.id, read('job.json').id);
assert.equal(settled.state.outcome.status, 'completed');
assert.equal(settled.state.outcome.result.commit, receipt.commit);
assert.deepEqual(read('settled-3.json'), settled);
assert.equal(hash(input.heartbeat), input.heartbeat_sha256);
assert.equal(hash(join(input.workspace, 'scripts/publish-logfile.mjs')), input.publisher_sha256);
assert.equal(hash(join(run, 'publisher-source.mjs')), input.publisher_sha256);
const before = readFileSync(join(run, 'LOGFILE-before.md'), 'utf8');
const after = readFileSync(join(run, 'LOGFILE-after.md'), 'utf8');
assert.equal(after.replace(/ \^log-[a-z0-9]+/g, ''), before.replace(/ \^log-[a-z0-9]+/g, ''));
const beforeIds = [...before.matchAll(/\^log-[a-z0-9]+/g)].map(match => match[0]);
const added = [...after.matchAll(/\^log-[a-z0-9]+/g)].map(match => match[0]).filter(id => !beforeIds.includes(id));
const authoredRootCount = before.split('\n').filter(line => /^[*-] /.test(line)).length;
const expectedAdded = authoredRootCount - read('snapshot-before.json').days.reduce((count, day) => count + day.entries.length, 0);
assert.ok(expectedAdded > 0);
assert.equal(added.length, expectedAdded);
for (const id of beforeIds) assert.equal(after.split(id).length, before.split(id).length);
const original = read('snapshot-before.json');
const published = read('snapshot-after.json');
const rootIds = data => data.days.flatMap(day => day.entries.map(entry => entry.id));
assert.equal(rootIds(published).length, authoredRootCount);
const newIds = added.map(id => id.slice(1));
for (const id of newIds) assert.equal(rootIds(published).filter(candidate => candidate === id).length, 1);
const recoveryLog = readFileSync(join(run, 'publisher-2.log'), 'utf8');
assert.ok(recoveryLog.includes('LOGFILE unchanged; no commit or deployment.'));
assert.equal(read('resumed-exit.json').code, 0);
assert.equal(read('crash-cleanup.json').stopped, true);
const status = spawnSync('/bin/ps', ['-axo', 'pid='], { encoding: 'utf8' });
assert.equal(status.status, 0);
const live = new Set(status.stdout.trim().split(/\s+/).map(Number));
for (const process of read('crash-cleanup.json').before) assert.equal(live.has(process.pid), false);
console.log(JSON.stringify({ passed: true, commit: receipt.commit, one_commit: true, one_push: true,
  same_task_recovered: true, unchanged_terminal_reopen: true, heartbeat_unchanged: true,
  publisher_unchanged: true, source_prose_preserved: true, new_ids: newIds, new_entries: expectedAdded }, null, 2));
